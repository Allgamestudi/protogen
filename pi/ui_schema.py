"""Settings shown on the web page: EN/RU names, help text, ranges.

T() = switch, S() = slider, C() = choice ("@emotions" = emotion list).
adv=True hides it under "All settings".
"""


def _item(kind, key, en, ru, en_help, ru_help, adv, **extra):
    d = {"key": key, "kind": kind, "adv": bool(adv),
         "label": {"en": en, "ru": ru}, "help": {"en": en_help, "ru": ru_help}}
    d.update(extra)
    return d


def T(key, en, ru, en_help, ru_help, adv=False):
    return _item("toggle", key, en, ru, en_help, ru_help, adv)


def S(key, lo, hi, step, unit, en, ru, en_help, ru_help, adv=False):
    return _item("slider", key, en, ru, en_help, ru_help, adv, min=lo, max=hi, step=step, unit=unit)


def C(key, options, en, ru, en_help, ru_help, adv=False):
    return _item("choice", key, en, ru, en_help, ru_help, adv, options=options)


