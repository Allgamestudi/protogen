    def _ease_soft(t):
        """Step response of a damped spring: starts gently, passes the target
        by about 6 % and settles. _ease_spring covers 75 % of the way in the
        first frame at 30 fps, so the morph itself was never seen."""
        if t <= 0.0:
            return 0.0
        if t >= 1.0:
            return 1.0
        damp, freq = 4.0, 4.5
        rest = lambda x: math.exp(-damp * x) * (math.cos(freq * x) + damp / freq * math.sin(freq * x))
