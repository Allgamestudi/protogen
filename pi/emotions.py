def _polygon_face(eid: str, donor=None):
    """An emotion without artwork, rasterised from its polygons into the same
    five parts the artwork has. The closed eye is the open one squashed flat.
    With a donor face, the mouth and the nose are the donor's."""
    import emotion_art
    eye = _EYE_SLOTS[0][eid]
    closed = eye.copy()
    cy = closed[:, 1].mean()
    closed[:, 1] = closed[:, 1] * 0.12 + cy * 0.88
    nose = [slot[eid] for slot in _EYE_SLOTS[1:]]
    mc, mo = _MOUTH_SLOTS[eid]
    masks = {
        "eye_open": _rasterize_poly(eye) / 255.0,
        "eye_closed": _rasterize_poly(closed) / 255.0,
        "nose": (_rasterize_polys(nose) if nose else np.zeros((config.H, config.W))) / 255.0,
        "mouth_closed": _rasterize_poly(mc) / 255.0,
        "mouth_open": _rasterize_poly(mo) / 255.0,
    }
    # These polygons were drawn the other way round (eye on the right); the
    # artwork has the eye on the left and the mouth on the right.
    masks = {k: np.ascontiguousarray(v[:, ::-1]) for k, v in masks.items()}
    if donor is not None:
        extras = masks["nose"].copy()
        extras[:, config.W // 2:] = 0.0          # keep what belongs to the eye (a brow)
        masks["nose"] = np.maximum(extras, donor.cov["nose"])
        masks["mouth_closed"] = donor.cov["mouth_closed"]
        masks["mouth_open"] = donor.cov["mouth_open"]
    return emotion_art.Face(masks)


class Layout:
    """Where the parts of a face are, for effects drawn on top of it."""
    __slots__ = ("catchlight", "eye_centre", "eye_pixels", "mouth_box")

    def __init__(self, face, highlight_at=0.68):
        eye = face.cov["eye_open"]
        ys, xs = np.nonzero(eye > 0.5)
        if len(xs) == 0:
            ys, xs = np.array([config.H // 2]), np.array([config.W // 4])
        self.eye_centre = (float(xs.mean()), float(ys.mean()))
        self.eye_pixels = list(zip(xs.tolist(), ys.tolist()))
        # highlight: upper part of the eye, on the side of the nose; the pixel
        # and its right neighbour must both be lit (the highlight is two wide)
        if getattr(face, "pupil_sdf", None) is not None:      # not on the pupil, nor right beside it
            import emotion_art
            eye = eye * (1.0 - emotion_art.from_sdf(face.pupil_sdf - 1.0))
        wide = eye[:, :-1] * eye[:, 1:] > 0.8
        cy, cx = np.nonzero(wide)
        if len(cx) == 0:
            cy, cx = ys, xs
        tx = xs.min() + highlight_at * (xs.max() - xs.min())
        ty = ys.min() + 0.30 * (ys.max() - ys.min())
        best = int(np.argmin((cx - tx) ** 2 + (cy - ty) ** 2))
        self.catchlight = (float(cx[best]), float(cy[best]))
        my, mx = np.nonzero(face.cov["mouth_open"] > 0.3)
        self.mouth_box = ((int(mx.min()), int(my.min()), int(mx.max()) + 1, int(my.max()) + 1)
                          if len(mx) else (0, 18, 40, 30))


