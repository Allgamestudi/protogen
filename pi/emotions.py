def _load_one(eid, eye_file=None):
    import emotion_art
    prefixes = ART_PREFIX.get(eid, ())
    prefixes = (prefixes,) if isinstance(prefixes, str) else prefixes
    for prefix in prefixes:
        face = emotion_art.load_png_face(ART_DIR, prefix, config.W, config.H, eye_file=eye_file)
        if face is None:
            continue
        if face.blink_sdf is None:
            # the lid line may be filed under the other spelling of the name
            for other in prefixes:
                blink = emotion_art.read_mask(
                    os.path.join(ART_DIR, f"{other}_blink_eye.png"), config.W, config.H)
                if blink is not None:
                    face.set_blink(blink)
                    break
        return face
    return None


