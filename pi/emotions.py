# ============================================================ resampling ====

def _poly_resample(poly: list, n: int) -> np.ndarray:
    """Resample a polygon to exactly *n* evenly-spaced vertices by arc length.

    This lets us morph between polygons that originally have different vertex
    counts - vertex i in the resampled version always corresponds to the same
    relative position along the contour.
    """
    pts = np.array(poly, dtype=np.float64)
    # close the loop for arc-length computation
    closed = np.vstack([pts, pts[0]])
    diffs  = np.diff(closed, axis=0)
    segs   = np.hypot(diffs[:, 0], diffs[:, 1])
    total  = segs.sum()
    if total == 0:
        return np.tile(pts[0], (n, 1))

    # cumulative arc lengths, starting at 0
    cuml = np.concatenate([[0.0], np.cumsum(segs)])
    # target arc positions (do NOT include the closing duplicate)
    targets = np.linspace(0.0, total, n, endpoint=False)

    out = np.empty((n, 2), dtype=np.float64)
    for i, t in enumerate(targets):
        j = np.searchsorted(cuml, t, side='right') - 1
        j = min(j, len(pts) - 1)
        j_next = (j + 1) % len(pts)
        seg_len = segs[j]
        if seg_len < 1e-12:
            out[i] = pts[j]
        else:
            frac = (t - cuml[j]) / seg_len
            out[i] = pts[j] * (1.0 - frac) + pts[j_next] * frac
    return out


# ================================================= normalised polygon sets ===

# For each slot (eye[0], eye[1], mouth) we normalise all emotions to the same
# vertex count (maximum across all emotions for that slot).

def _collect_slot_polys():
    """Return dicts keyed by emotion_id with resampled numpy arrays.

    Returns:
        eye_slots  : list of {emo_id: ndarray(N,2)}  - one dict per eye polygon
        mouth_slots: {emo_id: (closed_arr, open_arr)}
    """
    n_eye_slots = max(len(v[2]) for v in EMOTIONS.values())

    # Compute target vertex count per slot = max across all emotions
    eye_counts   = []
    for slot in range(n_eye_slots):
        mx = max(
            len(v[2][slot]) if slot < len(v[2]) else 0
            for v in EMOTIONS.values()
        )
        eye_counts.append(mx)

    mouth_count = max(len(v[3]) for v in EMOTIONS.values())

    eye_slots = [{} for _ in range(n_eye_slots)]
    mouth_slots = {}

    for eid, (_, _, eye_polys, mc, mo) in EMOTIONS.items():
        for slot in range(n_eye_slots):
            poly = eye_polys[slot] if slot < len(eye_polys) else eye_polys[-1]
            eye_slots[slot][eid] = _poly_resample(poly, eye_counts[slot])
        mouth_slots[eid] = (
            _poly_resample(mc, mouth_count),
            _poly_resample(mo, mouth_count),
        )

    return eye_slots, mouth_slots


_EYE_SLOTS, _MOUTH_SLOTS = _collect_slot_polys()

