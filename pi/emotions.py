def _rasterize_polys(poly_list_np: list) -> np.ndarray:
    """Rasterize a list of numpy (N,2) polygon arrays -> uint8 mask."""
    img = Image.new("L", (config.W, config.H), 0)
    d   = ImageDraw.Draw(img)
    for pts in poly_list_np:
        d.polygon(pts.ravel().tolist(), fill=255)
    return np.array(img, dtype=np.uint8)


def _rasterize_poly(pts_np: np.ndarray) -> np.ndarray:
    img = Image.new("L", (config.W, config.H), 0)
    ImageDraw.Draw(img).polygon(pts_np.ravel().tolist(), fill=255)
    return np.array(img, dtype=np.uint8)


