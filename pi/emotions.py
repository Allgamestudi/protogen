def _ease_spring(t: float) -> float:
    """Underdamped-spring ease-out - overshoots past 1.0 then settles.

    Input linear t in [0,1], output may briefly exceed 1.0 (overshoot) then
    oscillate back. Used for emotion transitions so polygon vertices
    spring/wobble into their target positions instead of sliding linearly.

    Tune via SPRING_PERIOD / SPRING_DECAY constants below.
    """
    if t <= 0.0:
        return 0.0
    if t >= 1.0:
        return 1.0
    period = 0.42       # smaller = faster oscillation (more jelly)
    decay  = 7.0        # larger = quicker settle (less wobble)
    s = period / 4.0
    return (2.0 ** (-decay * t)) * math.sin((t - s) * 2.0 * math.pi / period) + 1.0


def _interp_polys(polys_a: list, polys_b: list, t: float) -> list:
    """Linearly interpolate corresponding resampled polygon arrays."""
    inv = 1.0 - t
    return [a * inv + b * t for a, b in zip(polys_a, polys_b)]


def get_face_alpha(emotion_id: str, mouth_open_level: float) -> np.ndarray:
    """Single emotion, mouth morphed by mouth_open_level  in  [0,1].

    Vertices move - not just brightness fade.
    """
    eid  = emotion_id if emotion_id in MASKS else "angry"
    t    = max(0.0, min(1.0, mouth_open_level))
    inv  = 1.0 - t

    # mouth: vertex-interpolate closed->open
    mc, mo = _MOUTH_SLOTS[eid]
    mouth_np = mc * inv + mo * t

    eye_mask   = MASKS[eid]._eye_f
    mouth_mask = _rasterize_poly(mouth_np).astype(np.float32)
    return np.maximum(eye_mask, mouth_mask) / 255.0


def get_face_alpha_morph(
    emotion_from: str,
    emotion_to: str,
    blend: float,
    mouth_open_level: float,
) -> np.ndarray:
    """Vertex-morph transition between two emotions.

    blend=0.0 -> fully emotion_from
    blend=1.0 -> fully emotion_to

    Every polygon vertex travels in a straight line from its position in
    emotion_from to its position in emotion_to.  The mouth is additionally
    morphed by mouth_open_level on top of the emotion blend.
    """
    blend = max(0.0, min(1.0, blend))

    eid_a = emotion_from if emotion_from in MASKS else "angry"
    eid_b = emotion_to   if emotion_to   in MASKS else "angry"

    if blend == 0.0:
        return get_face_alpha(eid_a, mouth_open_level)
    if blend == 1.0:
        return get_face_alpha(eid_b, mouth_open_level)

    # springy ease - overshoots past 1.0 so vertices wobble into place
    eblend = _ease_spring(blend)
    inv_blend = 1.0 - eblend
    t_mouth   = max(0.0, min(1.0, mouth_open_level))
    inv_mouth = 1.0 - t_mouth

    # --- eye slots: morph vertex positions between emotions ---
    eye_polys_np = [
        slot[eid_a] * inv_blend + slot[eid_b] * eblend
        for slot in _EYE_SLOTS
    ]

    # --- mouth: first blend emotion vertices, then apply lip-sync open ---
    mc_a, mo_a = _MOUTH_SLOTS[eid_a]
    mc_b, mo_b = _MOUTH_SLOTS[eid_b]
    # closed position in the blended emotion
    mc_blend = mc_a * inv_blend + mc_b * eblend
    # open position in the blended emotion (lip-sync uses LINEAR mouth_open_level -
    # only the emotion-blend axis is sprung; lip-sync stays tight with audio)
    mo_blend = mo_a * inv_blend + mo_b * eblend
    mouth_np = mc_blend * inv_mouth + mo_blend * t_mouth

    return _rasterize_polys([*eye_polys_np, mouth_np]).astype(np.float32) / 255.0


# keep old name as alias so nothing else breaks
get_face_alpha_blend = get_face_alpha_morph


def get_face_alpha_animated(
    emotion_from: str,
    emotion_to: str,
    blend: float,
    mouth_open_level: float,
    blink_level: float = 0.0,
    eye_dx: float = 0.0,
    eye_dy: float = 0.0,
    nose_dy: float = 0.0,
) -> np.ndarray:
    """Full-featured face rendering: emotion morph + lip-sync + blink + eye-dart.

    Slot 0 of the eye polygons is treated as THE EYE - it gets blink-collapse
    and eye-dart translation.  Slots 1+ are nose / static accents - they morph
    between emotions but never move with the eye.

    blink_level 0..1 - vertically collapses the eye polygon toward its centroid.
    eye_dx, eye_dy   - translation applied only to slot 0.
    """
    blend = max(0.0, min(1.0, blend))
    eid_a = emotion_from if emotion_from in MASKS else "angry"
    eid_b = emotion_to   if emotion_to   in MASKS else "angry"
    # springy ease on emotion axis only (lip-sync/blink stay linear/real-time)
    eblend = _ease_spring(blend)
    inv_blend = 1.0 - eblend
    t_mouth   = max(0.0, min(1.0, mouth_open_level))
    inv_mouth = 1.0 - t_mouth
    blink     = max(0.0, min(1.0, blink_level))

    # --- polygons: emotion blend on all; blink/eye-dart only on slot 0 (eye) ---
    eye_polys_np = []
    for slot_idx, slot in enumerate(_EYE_SLOTS):
        poly = slot[eid_a] * inv_blend + slot[eid_b] * eblend
        if slot_idx == 0:                                 # only the actual eye
            if blink > 0.01:
                cy = poly[:, 1].mean()
                poly[:, 1] = poly[:, 1] * (1.0 - blink) + cy * blink
            if eye_dx != 0.0 or eye_dy != 0.0:
                poly[:, 0] += eye_dx
                poly[:, 1] += eye_dy
        else:
            # slots >=1 are the nose / static accents - emotion-morph only,
            # plus optional vertical nudge for the nose-twitch vignette
            if nose_dy != 0.0:
                poly[:, 1] += nose_dy
        eye_polys_np.append(poly)

    # --- mouth: emotion blend (springy) + lip-sync (linear/real-time) ---
    mc_a, mo_a = _MOUTH_SLOTS[eid_a]
    mc_b, mo_b = _MOUTH_SLOTS[eid_b]
    mc = mc_a * inv_blend + mc_b * eblend
    mo = mo_a * inv_blend + mo_b * eblend
    mouth_np = mc * inv_mouth + mo * t_mouth

    return _rasterize_polys([*eye_polys_np, mouth_np]).astype(np.float32) / 255.0


